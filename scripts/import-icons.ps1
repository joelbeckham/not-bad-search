param([Parameter(Mandatory=$true)][string]$ExtensionDirectory)
$ErrorActionPreference='Stop'
# Input: extracted official catppuccin-vsc-icons-1.26.0.vsix / extension directory.
$repo=Split-Path $PSScriptRoot -Parent
$source=Join-Path $ExtensionDirectory 'dist\mocha'
$theme=Get-Content (Join-Path $source 'theme.json') -Raw | ConvertFrom-Json
$assets=Join-Path $repo 'assets\catppuccin'
New-Item -ItemType Directory -Force "$assets\icons" | Out-Null
$utf8=New-Object Text.UTF8Encoding($false)
$mapping=[ordered]@{file=$theme.file;fileNames=$theme.fileNames;fileExtensions=$theme.fileExtensions}
[IO.File]::WriteAllText("$assets\mapping.json",($mapping | ConvertTo-Json -Depth 8),$utf8)
Copy-Item (Join-Path $ExtensionDirectory 'LICENSE.txt') "$assets\LICENSE.txt"
$ids=@($theme.file)+@($theme.fileNames.PSObject.Properties.Value)+@($theme.fileExtensions.PSObject.Properties.Value) | Sort-Object -Unique
$lines=[Collections.Generic.List[string]]::new()
$lines.Add('// Generated by scripts/import-icons.ps1 from Catppuccin Icons v1.26.0 (MIT).')
$lines.Add('pub(super) fn asset(id: &str) -> Option<(&''static str, &''static [u8])> {')
$lines.Add('    Some(match id {')
foreach($id in $ids){
    if($id -notmatch '^[a-zA-Z0-9_-]+$'){throw "Unexpected icon ID: $id"}
    Copy-Item (Join-Path $source $theme.iconDefinitions.$id.iconPath) "$assets\icons\$id.svg"
    $lines.Add(('        "{0}" => ("bytes://catppuccin/{0}.svg", include_bytes!("../assets/catppuccin/icons/{0}.svg")),' -f $id))
}
$lines.Add('        _ => return None,')
$lines.Add('    })')
$lines.Add('}')
[IO.File]::WriteAllLines((Join-Path $repo 'src\file_icon_assets.rs'),$lines,$utf8)
Write-Output "Imported $($ids.Count) file icons; $($theme.fileNames.PSObject.Properties.Name.Count) filenames; $($theme.fileExtensions.PSObject.Properties.Name.Count) extensions."
